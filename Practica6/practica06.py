# ─────────────────────────────────────────────────────────────────
# 2.2 — KDF basada en SHA-256 (familia SHA-2)
# NIST SP800-56A: Concat KDF con FixedInfo = AlgorithmID || PartyUInfo || PartyVInfo
# ─────────────────────────────────────────────────────────────────
def kdf(shared_secret_z, key_usage, entity_u, entity_v):
    # NIST: AlgorithmID || PartyUInfo || PartyVInfo
    fixed_info = key_usage + entity_u + entity_v
    ckdf = ConcatKDFHash(
        algorithm=hashes.SHA256(),
        length=32,           # 256 bits
        otherinfo=fixed_info # FixedInfo context
    )
    derived_key_k64 = base64.b64encode(ckdf.derive(shared_secret_z)).decode()
    return derived_key_k64

