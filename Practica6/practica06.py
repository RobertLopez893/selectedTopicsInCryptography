import base64
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.asymmetric.utils import (
    decode_dss_signature,
    encode_dss_signature,
)
from cryptography.hazmat.primitives.kdf.concatkdf import ConcatKDFHash
from cryptography.exceptions import InvalidSignature

# ─────────────────────────────────────────────────────────────────
# CONSTANTES COMPARTIDAS
# Curvas sobre campo primo — NIST SP800-186 Sección 3.2.1
# Solo curvas Weierstrass sobre GF(p), tal como exige el lab.
# ─────────────────────────────────────────────────────────────────
curve_map = {
    "P-224": ec.SECP224R1(),
    "P-256": ec.SECP256R1(),
    "P-384": ec.SECP384R1(),
    "P-521": ec.SECP521R1(),
}

# Hash recomendado por FIPS 186-5 — la fortaleza del hash debe
# igualar o superar la fortaleza de seguridad de la curva.
HASH_FOR_CURVE = {
    "P-224": hashes.SHA224(),
    "P-256": hashes.SHA256(),
    "P-384": hashes.SHA384(),
    "P-521": hashes.SHA512(),
}

