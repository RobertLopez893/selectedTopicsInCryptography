# 2.1 — Simulación de acuerdo de llaves ECDH
# Responsable: Emiliano
# ─────────────────────────────────────────────────────────────────
def simulate_diffie_hellman():
    print("\nAvailable NIST curves: P-224, P-256, P-384, P-521")
    select = input("Select a curve: ").strip().upper()
    while select not in curve_map:
        select = input("Invalid curve. Select a curve: ").strip().upper()
    curve = curve_map[select]

    select = input("Do you want to add FixedInfo? [0-No / Otherwise-Yes]: ")
    u_entity, v_entity, key_usage = b'', b'', b''
    if select != "0":
        u_entity  = (input("Enter User A identifier (e.g., Alice): ").strip() or "Alice").encode()
        v_entity  = (input("Enter User B identifier (e.g., Bob): ").strip() or "Bob").encode()
        key_usage = (input("Enter intended algorithm (e.g., AES-256-GCM): ").strip() or "AES-256-GCM").encode()

    # Generar llaves de Alice (a) y Bob (b)
    u_priv = ec.generate_private_key(curve)
    u_pub  = u_priv.public_key()
    v_priv = ec.generate_private_key(curve)
    v_pub  = v_priv.public_key()    # BUGFIX: era u_pub (copiaba la llave de Alice)

    # Serializar llaves públicas en PEM y guardar en archivos
    u_pub_pem = u_pub.public_bytes(
        encoding=serialization.Encoding.PEM,
        format=serialization.PublicFormat.SubjectPublicKeyInfo,
    )
    v_pub_pem = v_pub.public_bytes(
        encoding=serialization.Encoding.PEM,
        format=serialization.PublicFormat.SubjectPublicKeyInfo,
    )

    with open("aG_pub.pem", "wb") as f:
        f.write(u_pub_pem)
    with open("bG_pub.pem", "wb") as f:
        f.write(v_pub_pem)

    print(f"\n[aG] Llave pública de Alice (base64):\n{base64.b64encode(u_pub_pem).decode()}")
    print(f"\n[bG] Llave pública de Bob (base64):\n{base64.b64encode(v_pub_pem).decode()}")

    # Cada parte calcula el secreto compartido K = abG
    K  = u_priv.exchange(ec.ECDH(), v_pub)  # Alice: a * (bG)
    K2 = v_priv.exchange(ec.ECDH(), u_pub)  # Bob:   b * (aG)

    if K == K2:
        print("\n[✓] Secreto compartido igual en ambos lados (K == K2)")
    else:
        print("\n[✗] ERROR: los secretos no coinciden")

    print(f"\n[Step 1] Shared Secret K (Base64): {base64.b64encode(K).decode()}")
    print(f"[Step 2] Derived key k (256 bits, Base64): {kdf(K, key_usage, u_entity, v_entity)}")

# ── Ejecutar la simulación ECDH ───────────────────────────────────
simulate_diffie_hellman()