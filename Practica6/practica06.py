# ─────────────────────────────────────────────────────────────────
# 1.1 — Generación de par de llaves ECDSA
# Responsable: Roberto
# ─────────────────────────────────────────────────────────────────
def generar_par_llaves(archivo_priv, archivo_pub, curva_nombre="P-256"):
    """
    Genera un par de llaves ECDSA para la curva indicada.
    Guarda la llave privada y pública como base64 en archivos separados.
    """
    curva      = curve_map[curva_nombre]
    llave_priv = ec.generate_private_key(curva)
    llave_pub  = llave_priv.public_key()

    priv_der = llave_priv.private_bytes(
        encoding=serialization.Encoding.DER,
        format=serialization.PrivateFormat.PKCS8,
        encryption_algorithm=serialization.NoEncryption(),
    )
    pub_der = llave_pub.public_bytes(
        encoding=serialization.Encoding.DER,
        format=serialization.PublicFormat.SubjectPublicKeyInfo,
    )

    with open(archivo_priv, "w") as f:
        f.write(base64.b64encode(priv_der).decode())
    with open(archivo_pub, "w") as f:
        f.write(base64.b64encode(pub_der).decode())

    print(f"[OK] Par de llaves generado ({curva_nombre})")
    print(f"     Privada → {archivo_priv}")
    print(f"     Pública → {archivo_pub}")

# ─────────────────────────────────────────────────────────────────
# 1.2 — Generación de firma ECDSA
# Responsable: Roberto
# ─────────────────────────────────────────────────────────────────
def firmar(archivo_priv, archivo_mensaje, archivo_firma, curva_nombre="P-256"):
    """
    Genera la firma ECDSA de un archivo usando la llave privada indicada.
    Guarda el par (r, s) en un archivo de texto.
    """
    with open(archivo_priv, "r") as f:
        priv_der = base64.b64decode(f.read().strip())
    llave_priv = serialization.load_der_private_key(priv_der, password=None)

    with open(archivo_mensaje, "rb") as f:
        mensaje = f.read()

    # La librería genera k seguro, calcula R=k·G, aplica H(m) y computa (r,s)
    firma_der = llave_priv.sign(mensaje, ec.ECDSA(HASH_FOR_CURVE[curva_nombre]))
    r, s = decode_dss_signature(firma_der)

    with open(archivo_firma, "w") as f:
        f.write(f"r={r}\ns={s}\n")

    print(f"[OK] Firma guardada en: {archivo_firma}")
    print(f"     r = {hex(r)}")
    print(f"     s = {hex(s)}")

# ─────────────────────────────────────────────────────────────────
# 1.3 — Verificación de firma ECDSA
# Responsable: Hatziry Vitales Herrera
# ─────────────────────────────────────────────────────────────────
def verificar(archivo_pub, archivo_mensaje, archivo_firma, curva_nombre="P-256"):
    """
    Verifica la firma ECDSA (FIPS 186-5, Sec. 6.4.2).

    Pasos internos del algoritmo:
      1. Valida r, s en [1, n-1]
      2. Calcula e = H(m)
      3. w = s^-1 mod n
      4. u1 = e*w mod n  ,  u2 = r*w mod n
      5. X = u1*G + u2*Q
      6. Compara v = x_X mod n  con r

    Parámetros:
        archivo_pub     — archivo con la llave pública en base64
        archivo_mensaje — archivo con el mensaje original (bytes)
        archivo_firma   — archivo de texto con r=... / s=...
        curva_nombre    — debe coincidir con la curva usada al firmar

    Retorna:
        True  si la firma es válida
        False si la firma NO es válida
    """

    # Paso 1 — Cargar llave pública desde base64
    with open(archivo_pub, "r") as f:
        pub_der = base64.b64decode(f.read().strip())
    llave_pub = serialization.load_der_public_key(pub_der)

    # Paso 2 — Leer mensaje original
    with open(archivo_mensaje, "rb") as f:
        mensaje = f.read()

    # Paso 3 — Leer r y s, reconstruir firma en formato DER
    r, s = None, None
    with open(archivo_firma, "r") as f:
        for linea in f:
            linea = linea.strip()
            if linea.startswith("r="):
                r = int(linea[2:])
            elif linea.startswith("s="):
                s = int(linea[2:])

    if r is None or s is None:
        raise ValueError("Archivo de firma inválido: no se encontraron r y/o s.")

    firma_der = encode_dss_signature(r, s)

    # Paso 4 — Verificar (pasos 2-6 ejecutados internamente por la librería)
    # Si la firma es válida, verify() termina sin error.
    # Si es inválida, lanza InvalidSignature.
    try:
        llave_pub.verify(firma_der, mensaje, ec.ECDSA(HASH_FOR_CURVE[curva_nombre]))
        print("[✓] Firma VÁLIDA — el mensaje no ha sido alterado.")
        return True
    except InvalidSignature:
        print("[✗] Firma INVÁLIDA — el mensaje fue alterado o la firma es incorrecta.")
        return False

